def export_txt(
    output_path: str,
    title: str,
    author: str,
    description: str,
    chapters: List[Tuple[str, str]],
    lang: str = "zh",
) -> str:
    """生成规范排版的纯文本 TXT（lang='en' 输出英文版式：英文标签、无全角缩进）。"""
    is_en = (lang or "zh").lower() == "en"
    L = _labels(lang)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    total_words = sum(_word_count(text) for _, text in chapters)

    lines: List[str] = [
        title if is_en else f"《{title}》",
        f"{L['by']}{author}",
        L["txt_scale"].format(n=len(chapters), w=total_words),
        L["txt_date"].format(d=time.strftime("%Y-%m-%d")),
        "=" * 48,
        L["synopsis"],
        description.strip(),
        "=" * 48,
        "",
    ]

    for i, (ctitle, ctext) in enumerate(chapters, 1):
        lines.append(f"\n\n{'=' * 20} {ctitle} {'=' * 20}\n")
        paras = _md_to_paragraphs(ctext)
        for p in paras:
            # 中文全角空格标准段首缩进；英文版式不加缩进
            lines.append(f"{L['txt_indent']}{p}")
            lines.append("")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines).strip() + "\n")
    return output_path


def export_all(
    proj: Any,
    formats: Optional[Sequence[str]] = None,
    strip: bool = True,
    lang: str = "zh",
) -> Dict[str, str]:
    """一键为项目导出指定格式小说。

    formats 默认为 ['epub', 'html', 'txt']。
    strip=True（默认）时剥离 W/C 设定编号锚点，产出出版净稿；
    审校与 audit 请使用章节文件与 manuscript/ 成书（保留锚点）。
    lang='en' 导出英文版：读 chapters_en/、产物落 dist_en/、标题加 (English Edition)。
    """
    is_en = (lang or "zh").lower() == "en"
    if formats is None or "all" in formats:
        formats = ["epub", "html", "txt", "pdf"]

    cfg = proj.config()
    title = cfg.get("title", proj.name)
    if is_en:
        title = "%s (English Edition)" % title
    author = cfg.get("author", "FutureTxt AI Writer")

    if is_en:
        # 英文版简介优先用译好的 blurb_en.md
        description = (cfg.get("premise") or title)
        blurb_file = proj.path("blurb_en.md")
        if os.path.exists(blurb_file):
            with open(blurb_file, encoding="utf-8") as f:
                description = f.read().strip() or description
    else:
        concept_raw = ""
        concept_path = proj.f_concept()
        if os.path.exists(concept_path):
            with open(concept_path, encoding="utf-8") as f:
                concept_raw = f.read()
        # 提取简介
        m_intro = re.search(r"## 故事前提展开[^\n]*\n([\s\S]*?)(?=\n##|$)", concept_raw)
        description = m_intro.group(1).strip() if m_intro else (cfg.get("premise") or title)

    # 收集章节（英文版读 chapters_en/）
    if is_en:
        en_dir = proj.path("chapters_en")
        chapter_files = sorted(
            os.path.join(en_dir, f) for f in os.listdir(en_dir)
            if f.endswith(".md")) if os.path.isdir(en_dir) else []
        if not chapter_files:
            raise RuntimeError(
                "尚无英文章节，请先执行：python pipeline/run.py translate %s" % proj.name)
    else:
        chapter_files = proj.list_chapters()
        if not chapter_files:
            raise RuntimeError("项目尚无章节文件，请先执行 draft 阶段生成正文。")

    # 作品形态：短篇单篇不显示「第 N 章」分隔，篇名即书名
    is_short = str(cfg.get("work_type", "novel")).lower() == "short"
    valid_ids = _defined_anchor_ids(proj) if strip else None
    daily_titles = _defined_daily_titles(proj) if strip else None
    if strip:
        # 简介同样可能是锚点来源（如「平台规则 W1：…」「调度客服 C1…」），必须一并剥离
        description = strip_anchors(description, valid_ids, daily_titles)
    chapters: List[Tuple[str, str]] = []
    for path in chapter_files:
        with open(path, encoding="utf-8") as f:
            text = f.read()
        if is_short:
            text = re.sub(r"^#\s*第\s*\d+\s*章[^\n]*\n+", "", text, count=1)
        if strip:
            text = strip_anchors(text, valid_ids, daily_titles)
        no = re.search(r"chapter_(\d+)", os.path.basename(path))
        def_title = f"第 {int(no.group(1))} 章" if no else os.path.basename(path)
        ch_title = title if is_short else _extract_title(text, def_title)
        chapters.append((ch_title, text))

    dist_dir = proj.path("dist_en" if is_en else "dist")
    os.makedirs(dist_dir, exist_ok=True)
    lang_key = "en" if is_en else "zh"
    results = {}

    for fmt in formats:
        fmt = fmt.lower().strip()
        if fmt == "epub":
            out_file = os.path.join(dist_dir, f"{title}.epub")
            export_epub(out_file, title, author, description, chapters, lang=lang_key)
            results["epub"] = out_file
        elif fmt == "html":
            out_file = os.path.join(dist_dir, f"{title}.html")
            export_html(out_file, title, author, description, chapters, lang=lang_key)
            results["html"] = out_file
        elif fmt == "txt":
            out_file = os.path.join(dist_dir, f"{title}.txt")
            export_txt(out_file, title, author, description, chapters, lang=lang_key)
            results["txt"] = out_file
        elif fmt == "pdf":
            # 无 TeX 依赖的中文 PDF（子集化嵌入系统中文字体）；找不到字体时优雅跳过
            out_file = os.path.join(dist_dir, f"{title}.pdf")
            try:
                from pdf import export_pdf
                export_pdf(out_file, title, author, description, chapters)
                results["pdf"] = out_file
            except Exception as e:  # noqa: BLE001
                print(f"  ⚠ 跳过 PDF（{str(e)[:80]}）")

    return results
