def _labels(lang: str) -> Dict[str, str]:
    return _LABELS.get((lang or "zh").lower(), _LABELS["zh"])


# 仅认定义位置：`**W1 标题**`、`**W1**`、`- W1：…`、`| **W1** |`；
# 正文里的普通词（如试剂 C12）不算定义，避免误剥。
_ANCHOR_ID_DEF_RE = re.compile(r"(?:\*\*\s*|^\s*[-*•]?\s*)([WC]\d+)(?![A-Za-z0-9])", re.M)


def _defined_anchor_ids(proj: Any) -> "set[str]":
    """从本项目世界观/角色文档提取已定义的设定编号（W1、C3…）。"""
    ids: "set[str]" = set()
    for getter in ("f_world", "f_characters"):
        getter_fn = getattr(proj, getter, None)
        if not callable(getter_fn):
            continue
        try:
            path = getter_fn()
        except Exception:
            continue
        if path and os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                ids |= set(_ANCHOR_ID_DEF_RE.findall(f.read()))
    return ids


def _defined_daily_titles(proj: Any) -> List[str]:
    """提取世界观文档「日常细节」清单条目标题（如「起床与光照」），用于剥离标题括号标签。"""
    getter_fn = getattr(proj, "f_world", None)
    if not callable(getter_fn):
        return []
    try:
        path = getter_fn()
    except Exception:
        return []
    if not (path and os.path.exists(path)):
        return []
    with open(path, encoding="utf-8") as f:
        src = f.read()
    m = re.search(r"日常细节[^\n]*\n((?:[ \t]+\d+\.[^\n]*\n?)+)", src)
    if not m:
        return []
    return [t.strip() for t in re.findall(r"[ \t]+\d+\.\s*\*\*([^*\n]+)\*\*", m.group(1))]


def strip_anchors(
    text: str,
    valid_ids: Optional["set[str]"] = None,
    daily_titles: Optional[List[str]] = None,
) -> str:
    """剥离正文中的锚点，产出出版级净稿。

    三族锚点：W/C 硬性设定与角色规则（（W5）（C3、C5）、根据 W4，、W2 规定、裸编号）、
    日常细节清单编号（（日常细节2）、（见文化日常细节第11条）、根据日常细节13，）、
    清单条目标题标签（（起床与光照））。非引用的行文（「一段日常细节」「日常细节中的一环」）保留。
    裸编号仅限项目文档定义过的编号，防误伤 W3C、C12；
    会致病句的上下文（满足…而、触发…——、符合…规定、中提到的、well within…）先定向改写再剥离。
    反引号代码段（哈希、实验编号，如 `3F9A…C2E7`）整体保护，绝不改动。
    """
    # 0) 代码段处理：内容恰好是整条规则编号的代码段（如 `W8`）视为锚点直接剥离；
    #    其余代码段（哈希、单位、编号组合等）整体保护，防止误剥
    spans: List[str] = []

    def _mask_span(m: "re.Match[str]") -> str:
        if valid_ids and m.group(0)[1:-1].strip() in valid_ids:
            return ""
        spans.append(m.group(0))
        return "\x00%d\x00" % (len(spans) - 1)

    text = re.sub(r"`[^`\n]+`", _mask_span, text)
    # 1) 日常细节族：括号标签 + 条目标题标签
    text = _ANCHOR_RE_DAILY_PAREN.sub("", text)
    for t in daily_titles or []:
        t = t.strip()
        if t:
            text = text.replace("（%s）" % t, "").replace("(%s)" % t, "")
    # 2) W/C 括号锚点
    text = _ANCHOR_RE_PAREN.sub("", text)
    # 3) 两族引导式
    text = _ANCHOR_RE_DAILY_LEAD.sub(lambda m: m.group("pre"), text)
    text = _ANCHOR_RE_LEAD.sub(lambda m: m.group("pre"), text)
    # 4) 病句上下文定向改写——须在挂接式/裸删之前（如「符合 W3 规定」整体改写，防止拆剩「符合。」）
    for pat, repl in _ANCHOR_FIXUPS:
        text = pat.sub(repl, text)
    # 5) 挂接式与「所描述的」引用
    text = _ANCHOR_RE_RULE.sub("", text)
    text = _ANCHOR_RE_DAILY_REF.sub("", text)
    # 6) 裸编号（限已定义编号）
    if valid_ids:
        text = _ANCHOR_RE_BARE.sub(
            lambda m: "" if m.group(0) in valid_ids else m.group(0), text)
    # 7) 清理剥离残渣：连续空格、汉字间空格、悬空标点、空括号、多余空行
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"(?<=[一-鿿])[ \t]+(?=[一-鿿])", "", text)
    text = re.sub(r"\s+([。．！？；，、：])", r"\1", text)
    text = re.sub(r"（\s*）", "", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    # 8) 还原代码段
    text = re.sub(r"\x00(\d+)\x00", lambda m: spans[int(m.group(1))], text)
    return text


def export_epub(
    output_path: str,
    title: str,
    author: str,
    description: str,
    chapters: List[Tuple[str, str]],
    keywords: Optional[List[str]] = None,
    lang: str = "zh",
) -> str:
    """生成合规的 EPUB 3.0 / 2.0 双兼容电子书文件。

    chapters: [(章节标题, 章节正文markdown)]
    lang='en' 时使用英文界面文案与 en 语言标记（英文版导出）。
    """
    L = _labels(lang)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    epub_id = f"futuretxt-{int(time.time())}"
    date_str = time.strftime("%Y-%m-%d")

    css = """
body {
    font-family: -apple-system, "PingFang SC", "Microsoft YaHei", "Source Han Sans CN", serif;
    line-height: 1.85;
    margin: 5% 8%;
    color: #2c3e50;
}
h1, h2 {
    font-family: "PingFang SC", "Microsoft YaHei", sans-serif;
    color: #1a252f;
    text-align: center;
    margin-top: 1.5em;
    margin-bottom: 1.2em;
    font-weight: 600;
}
.chapter-title {
    border-bottom: 1px solid #e2e8f0;
    padding-bottom: 0.6em;
    font-size: 1.6em;
}
p {
    text-indent: 2em;
    margin: 0.8em 0;
    text-align: justify;
}
.book-cover {
    text-align: center;
    margin-top: 25%;
}
.book-title {
    font-size: 2.2em;
    margin-bottom: 0.3em;
    color: #0f172a;
    font-weight: bold;
}
.book-author {
    font-size: 1.1em;
    color: #64748b;
    margin-bottom: 2em;
}
.book-intro {
    text-align: left;
    display: inline-block;
    max-width: 80%;
    background: #f8fafc;
    border-left: 4px solid #3b82f6;
    padding: 1.2em 1.5em;
    border-radius: 4px;
    font-size: 0.95em;
    color: #334155;
}
.book-meta {
    margin-top: 2em;
    font-size: 0.85em;
    color: #94a3b8;
}
"""

    container_xml = """<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
    <rootfiles>
        <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
    </rootfiles>
</container>"""

    # 封面/扉页 HTML
    intro_html = f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="{L['xml_lang']}">
<head>
    <title>{html.escape(title)}</title>
    <link rel="stylesheet" type="text/css" href="style.css"/>
</head>
<body>
    <div class="book-cover">
        <div class="book-title">{html.escape(title)}</div>
        <div class="book-author">{L['by']}{html.escape(author)}</div>
        <div class="book-intro">
            <strong>{L['synopsis']}</strong><br/>
            {html.escape(description).replace(chr(10), '<br/>')}
        </div>
        <div class="book-meta">
            {L['epub_meta'].format(n=len(chapters), date=date_str)}
        </div>
    </div>
</body>
</html>"""

    # 逐章 XHTML
    chapter_files: List[Tuple[str, str, str]] = []  # (filename, title, content)
    for i, (ch_title, ch_text) in enumerate(chapters, 1):
        filename = f"chapter_{i:03d}.xhtml"
        paras = _md_to_paragraphs(ch_text)
        paras_html = "\n".join(f"        <p>{html.escape(p)}</p>" for p in paras)
        ch_html = f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="{L['xml_lang']}">
<head>
    <title>{html.escape(ch_title)}</title>
    <link rel="stylesheet" type="text/css" href="style.css"/>
</head>
<body>
    <h1 class="chapter-title">{html.escape(ch_title)}</h1>
{paras_html}
</body>
</html>"""
        chapter_files.append((filename, ch_title, ch_html))

    # Nav XHTML
    nav_items = "\n".join(
        f'            <li><a href="{fname}">{html.escape(ctitle)}</a></li>'
        for fname, ctitle, _ in chapter_files
    )
    nav_xhtml = f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="{L['xml_lang']}">
<head>
    <title>{L['toc']}</title>
    <link rel="stylesheet" type="text/css" href="style.css"/>
</head>
<body>
    <nav epub:type="toc" id="toc">
        <h1>{L['toc']}</h1>
        <ol>
            <li><a href="cover.xhtml">{L['cover_toc']}</a></li>
{nav_items}
        </ol>
    </nav>
</body>
</html>"""

    # NCX (EPUB 2 兼容)
    ncx_points = [
        f"""    <navPoint id="navpoint-1" playOrder="1">
        <navLabel><text>{L['cover_toc']}</text></navLabel>
        <content src="cover.xhtml"/>
    </navPoint>"""
    ]
    for idx, (fname, ctitle, _) in enumerate(chapter_files, 2):
        ncx_points.append(f"""    <navPoint id="navpoint-{idx}" playOrder="{idx}">
        <navLabel><text>{html.escape(ctitle)}</text></navLabel>
        <content src="{fname}"/>
    </navPoint>""")
    ncx_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1">
    <head>
        <meta name="dtb:uid" content="{epub_id}"/>
        <meta name="dtb:depth" content="1"/>
        <meta name="dtb:totalPageCount" content="0"/>
        <meta name="dtb:maxPageNumber" content="0"/>
    </head>
    <docTitle><text>{html.escape(title)}</text></docTitle>
    <navMap>
{chr(10).join(ncx_points)}
    </navMap>
</ncx>"""

    # OPF Package
    manifest_items = [
        '<item id="style" href="style.css" media-type="text/css"/>',
        '<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>',
        '<item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>',
        '<item id="cover" href="cover.xhtml" media-type="application/xhtml+xml"/>',
    ]
    spine_items = [
        '<itemref idref="cover"/>',
    ]
    for i, (fname, _, _) in enumerate(chapter_files, 1):
        item_id = f"ch_{i:03d}"
        manifest_items.append(f'<item id="{item_id}" href="{fname}" media-type="application/xhtml+xml"/>')
        spine_items.append(f'<itemref idref="{item_id}"/>')

    opf_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="BookID">
    <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
        <dc:identifier id="BookID">{epub_id}</dc:identifier>
        <dc:title>{html.escape(title)}</dc:title>
        <dc:creator>{html.escape(author)}</dc:creator>
        <dc:language>{L['xml_lang']}</dc:language>
        <dc:description>{html.escape(description)}</dc:description>
        <dc:date>{date_str}</dc:date>
        <meta property="dcterms:modified">{time.strftime('%Y-%m-%dT%H:%M:%SZ')}</meta>
    </metadata>
    <manifest>
        {chr(10).join('        ' + x for x in manifest_items)}
    </manifest>
    <spine toc="ncx">
        {chr(10).join('        ' + x for x in spine_items)}
    </spine>
</package>"""

    # 写入 zip 文件
    with zipfile.ZipFile(output_path, "w") as zf:
        # 1. 规范要求：mimetype 必须首个入包且不压缩
        zf.writestr("mimetype", "application/epub+zip", compress_type=zipfile.ZIP_STORED)
        # 2. 容器与资源
        zf.writestr("META-INF/container.xml", container_xml, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/content.opf", opf_content, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/toc.ncx", ncx_content, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/nav.xhtml", nav_xhtml, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/style.css", css, compress_type=zipfile.ZIP_DEFLATED)
        zf.writestr("OEBPS/cover.xhtml", intro_html, compress_type=zipfile.ZIP_DEFLATED)
        for fname, _, content in chapter_files:
            zf.writestr(f"OEBPS/{fname}", content, compress_type=zipfile.ZIP_DEFLATED)

    return output_path


